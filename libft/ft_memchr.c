#include "libft.h"

void	*ft_memchr(const void *s, int c, size_t n)
{
	const unsigned char	*s_cast;
	unsigned char		c_cast;

	s_cast = (const unsigned char *)s;
	c_cast = (unsigned char)c;
	while (n--)
	{
		if (c_cast == *s_cast)
			return ((void *)s_cast);
		s_cast++;
	}
	return (NULL);
}
